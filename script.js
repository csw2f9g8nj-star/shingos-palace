function submitFormWithProgress(form, endpoint, statusElement, submitButton, successMessageKey, headers = {}) {
  return new Promise((resolve, reject) => {
    const request = new XMLHttpRequest();
    request.open("POST", endpoint);
    request.setRequestHeader("Accept", "application/json");
    Object.entries(headers).forEach(([key, value]) => {
      if (value) request.setRequestHeader(key, value);
    });

    request.upload.addEventListener("progress", (event) => {
      if (form !== dogProfileForm || !event.lengthComputable || !vaccinationUploadProgress || !vaccinationUploadBar) return;
      vaccinationUploadProgress.hidden = false;
      const percent = Math.round((event.loaded / event.total) * 100);
      vaccinationUploadBar.style.width = `${percent}%`;
      if (vaccinationUploadStatus) vaccinationUploadStatus.textContent = t("vaccinationUploadProgress");
    });

    request.addEventListener("load", () => {
      let payload = {};
      try {
        payload = JSON.parse(request.responseText || "{}");
      } catch (error) {
        payload = {};
      }

      if (request.status >= 200 && request.status < 300 && payload.ok !== false) {
        if (statusElement) statusElement.textContent = payload.message || t(successMessageKey);
        if (vaccinationUploadStatus && form === dogProfileForm) vaccinationUploadStatus.textContent = t("vaccinationUploadSuccess");
        resolve(payload);
        return;
      }

      reject(new Error(payload.error || t("bookingError")));
    });

    request.addEventListener("error", () => reject(new Error(t("bookingError"))));
    request.addEventListener("abort", () => reject(new Error(t("bookingError"))));
    const formData = new FormData(form);
    if (form === bookingForm) {
      updatePrimaryPetFields();
      formData.set("petsJson", bookingPetsJson?.value || "[]");
      formData.set("petCount", bookingPetCountField?.value || "1");
      formData.set("petType", primaryPetTypeField?.value || "dog");
      formData.set("dogName", primaryPetNameField?.value || "");
      formData.set("breed", primaryBreedField?.value || "");
      formData.set("spayedNeutered", primarySpayedNeuteredField?.value || "");
      formData.set("rabiesVaccinationUpToDate", primaryRabiesField?.value || "");
    }
    const breedValue = form === bookingForm ? "" : finalBreedValue(form);
    if (breedValue && formData.has("breed")) {
      formData.set("breed", breedValue);
    }
    request.send(formData);
  });
}

function calculateBookingUnits() {
  if (!dropoffDateInput?.value || !pickupDateInput?.value) {
    return 1;
  }

  const start = new Date(`${dropoffDateInput.value}T00:00:00`);
  const end = new Date(`${pickupDateInput.value}T00:00:00`);
  const diffDays = Math.round((end - start) / (1000 * 60 * 60 * 24));

  return Math.max(1, diffDays || 1);
}

